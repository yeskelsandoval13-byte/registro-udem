USE RegistroUdeM;
GO

CREATE TABLE Personas (
    PersonaId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    Nombre NVARCHAR(80) NOT NULL,
    Apellido NVARCHAR(80) NOT NULL,
    Documento NVARCHAR(30) NOT NULL UNIQUE,
    Telefono NVARCHAR(25) NOT NULL,
    Email NVARCHAR(120) NULL,
    TipoPersona CHAR(1) NOT NULL CHECK (TipoPersona IN ('E','D','A')),
    CreadoEn DATETIME2(0) NOT NULL DEFAULT SYSDATETIME()
);
GO

CREATE TABLE Carreras (
    CarreraId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    Codigo NVARCHAR(20) NOT NULL UNIQUE,
    Nombre NVARCHAR(100) NOT NULL,
    Facultad NVARCHAR(80) NOT NULL,
    CreditosTotales INT NOT NULL,
    Activa BIT NOT NULL DEFAULT 1
);
GO

CREATE TABLE Estudiantes (
    EstudianteId UNIQUEIDENTIFIER PRIMARY KEY,
    CarreraId UNIQUEIDENTIFIER NOT NULL,
    Carnet NVARCHAR(20) NOT NULL UNIQUE,
    FechaIngreso DATE NOT NULL,
    Estado NVARCHAR(20) NOT NULL,
    Indice DECIMAL(5,2) NOT NULL DEFAULT 0,
    FOREIGN KEY (EstudianteId) REFERENCES Personas(PersonaId),
    FOREIGN KEY (CarreraId) REFERENCES Carreras(CarreraId)
);
GO

CREATE TABLE Docentes (
    DocenteId UNIQUEIDENTIFIER PRIMARY KEY,
    Especialidad NVARCHAR(80) NOT NULL,
    GradoAcademico NVARCHAR(40) NOT NULL,
    Activo BIT NOT NULL DEFAULT 1,
    FOREIGN KEY (DocenteId) REFERENCES Personas(PersonaId)
);
GO

CREATE TABLE Administrativos (
    AdministrativoId UNIQUEIDENTIFIER PRIMARY KEY,
    Cargo NVARCHAR(60) NOT NULL,
    Departamento NVARCHAR(60) NOT NULL,
    FOREIGN KEY (AdministrativoId) REFERENCES Personas(PersonaId)
);
GO

CREATE TABLE Asignaturas (
    AsignaturaId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    Codigo NVARCHAR(20) NOT NULL UNIQUE,
    Nombre NVARCHAR(100) NOT NULL,
    Creditos INT NOT NULL,
    CarreraId UNIQUEIDENTIFIER NOT NULL,
    Activa BIT NOT NULL DEFAULT 1,
    FOREIGN KEY (CarreraId) REFERENCES Carreras(CarreraId)
);
GO

CREATE TABLE Matriculas (
    MatriculaId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    EstudianteId UNIQUEIDENTIFIER NOT NULL,
    AsignaturaId UNIQUEIDENTIFIER NOT NULL,
    Periodo NVARCHAR(20) NOT NULL,
    Nota DECIMAL(5,2) NOT NULL DEFAULT 0,
    Estado NVARCHAR(20) NOT NULL,
    Fecha DATETIME2(0) NOT NULL DEFAULT SYSDATETIME(),
    FOREIGN KEY (EstudianteId) REFERENCES Estudiantes(EstudianteId),
    FOREIGN KEY (AsignaturaId) REFERENCES Asignaturas(AsignaturaId)
);
GO

CREATE TABLE Pagos (
    PagoId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    EstudianteId UNIQUEIDENTIFIER NOT NULL,
    Monto DECIMAL(12,2) NOT NULL,
    Concepto NVARCHAR(30) NOT NULL,
    Fecha DATETIME2(0) NOT NULL DEFAULT SYSDATETIME(),
    Pagado BIT NOT NULL DEFAULT 1,
    Referencia NVARCHAR(40) NULL,
    FOREIGN KEY (EstudianteId) REFERENCES Estudiantes(EstudianteId)
);
GO

CREATE TABLE Becas (
    BecaId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    EstudianteId UNIQUEIDENTIFIER NOT NULL,
    Tipo NVARCHAR(30) NOT NULL,
    Porcentaje DECIMAL(5,2) NOT NULL,
    Activa BIT NOT NULL DEFAULT 1,
    Observacion NVARCHAR(200) NULL,
    FOREIGN KEY (EstudianteId) REFERENCES Estudiantes(EstudianteId)
);
GO
